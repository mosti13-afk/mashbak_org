// Generates supabase/seed.sql from the default CMS content. Run: node --experimental-strip-types scripts/gen-seed.ts
import { writeFileSync } from "node:fs";
import { defaultFaqs, defaultPrograms, defaultReviews, defaultSettings } from "../src/lib/content.ts";

const GCS = "https://storage.googleapis.com/mashbak-public/reviews/avatars/00000000-0000-0000-0000-000000000000/";
const photos: Record<string, string> = {
  "rev-sahar": GCS + "01a1aca5-255e-77ed-bba4-10217bb7e1de.jpg",
  "rev-mahmoud": GCS + "01a1aca7-1585-7507-a28f-2466db5b555e.jpg",
  "rev-manar": GCS + "01a1b9f6-2153-75ec-aa14-8fa9e16ec628.jpg",
};
const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

let sql = "-- Default content for Mashbak v2 (generated by scripts/gen-seed.ts)\n\n";
for (const p of defaultPrograms) {
  sql += `insert into public.programs (slug, title, summary, body, for_who, duration, sessions, benefits, color, icon, sort_order, is_active) values (${q(p.slug)}, ${j(p.title)}, ${j(p.summary)}, ${j(p.body)}, ${j(p.for_who)}, ${j(p.duration)}, ${j(p.sessions)}, ${j(p.benefits)}, ${q(p.color)}, ${q(p.icon)}, ${p.sort_order}, ${p.is_active}) on conflict (slug) do nothing;\n`;
}
sql += "\n";
for (const f of defaultFaqs) {
  sql += `insert into public.faqs (question, answer, sort_order, is_active) values (${j(f.question)}, ${j(f.answer)}, ${f.sort_order}, ${f.is_active});\n`;
}
sql += "\n";
for (const r of defaultReviews) {
  sql += `insert into public.member_reviews (name, role_title, organization, photo_url, quote, sort_order, is_active) values (${j(r.name)}, ${j(r.role_title)}, ${q(r.organization)}, ${q(photos[r.id] ?? r.photo_url)}, ${j(r.quote)}, ${r.sort_order}, ${r.is_active});\n`;
}
sql += "\n";
const settings = { ...defaultSettings, floatingAvatars: Object.values(photos) };
for (const [k, v] of Object.entries(settings)) {
  sql += `insert into public.site_settings (key, value) values (${q(k)}, ${j(v)}) on conflict (key) do update set value = excluded.value;\n`;
}
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql", sql.length);
